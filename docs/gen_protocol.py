"""Builds docs/protocol.md (FR-029, T124) from the contracts in specs/001-pc-programmer-protocol/contracts:
the protocol, the package format and the internal interfaces, with a short guide in front. The contracts
stay the single source; `--check` fails when docs/protocol.md is out of date (CI)."""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTRACTS = ROOT / "specs" / "001-pc-programmer-protocol" / "contracts"
OUT = ROOT / "docs" / "protocol.md"
PARTS = [("protocol.md", "protocol"), ("package-format.md", "package-format"), ("chip-engine.md", "chip-engine")]

HEAD = """\
<!-- Generated by docs/gen_protocol.py from specs/001-pc-programmer-protocol/contracts — edit the contracts,
     then run `python docs/gen_protocol.py`. -->
# PADAUK smart programmer protocol

A description for those writing their own client or a firmware port. Three parts:

1. [PC ⇄ programmer protocol](#protocol) — frames, session, commands, operations, events, status codes.
2. [Firmware package format](#package-format) — what the client sends and the programmer stores.
3. [Internal firmware interfaces](#chip-engine) — the core, the IC engine, power, controls.

References such as FR-0xx, SC-0xx, R9 lead to the specification
[`specs/001-pc-programmer-protocol`](../specs/001-pc-programmer-protocol/spec.md) (requirements, success criteria,
decisions in `research.md`).

## Versioning

- **Protocol 1.1** (1.1 added the diagnostic trace `TRACE_SET` / `EVT_TRACE`). The version is carried by `HELLO` / `GET_INFO` (`proto_major`, `proto_minor`). A different major version →
  `PROTO_VERSION`, and the session is not opened. The minor version grows when commands, events, codes, or fields are added at the
  end of the payload: the client MUST ignore extra bytes at the end of a response, and an unknown command code gives
  `UNKNOWN_COMMAND` without dropping the session (§3).
- **Package format 1** (`format_version` in the header). An unknown format → `PKG_HEADER_INVALID`.
- **Build capabilities** — `GET_INFO.capabilities`: the firmware may lack some features (for example,
  `MEASURE_MASTER` or `PATCH`), and the client checks the bit before offering a feature.
- **The IC table** lives only in the firmware (`LIST_CHIPS`): a new IC does not need a new client.

## Status codes

The full list is [§6 of the protocol](#6-status-codes): `0x0000` — success, `0x01xx` — frame, session, and programmer
state, `0x02xx` — package checks, `0x03xx` — storage, `0x04xx` — IC operations
(including supply faults `VDD_FAULT` / `VPP_FAULT`).

## Mapping to `easypdkprog`

The table of `pdkprog` subcommands and protocol commands corresponding to the `easypdkprog` subcommands is [§7
of the protocol](#7-mapping-to-easypdkprog-commands-fr-030).
"""


def demote(text: str) -> str:
    """Every heading one level down, so each contract becomes a section of one document."""
    return re.sub(r"^(#+) ", lambda m: "#" + m.group(1) + " ", text, flags=re.M)


def build() -> str:
    out = [HEAD]
    for name, anchor in PARTS:
        text = (CONTRACTS / name).read_text(encoding="utf-8").strip()
        out.append(f'\n<a id="{anchor}"></a>\n\n' + demote(text) + "\n")
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if docs/protocol.md is out of date")
    a = ap.parse_args()
    text = build()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/protocol.md is out of date: run python docs/gen_protocol.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
