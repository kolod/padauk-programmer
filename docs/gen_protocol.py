"""Builds docs/protocol.md (FR-029, T124) from the contracts in specs/001-pc-programmer-protocol/contracts:
the protocol, the package format and the internal interfaces, with a short guide in front. The contracts
stay the single source; `--check` fails when docs/protocol.md is out of date (CI)."""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTRACTS = ROOT / "specs" / "001-pc-programmer-protocol" / "contracts"
OUT = ROOT / "docs" / "protocol.md"
PARTS = [("protocol.md", "protocol"), ("package-format.md", "package-format"), ("chip-engine.md", "chip-engine")]

HEAD = """\
<!-- Generated by docs/gen_protocol.py from specs/001-pc-programmer-protocol/contracts — edit the contracts,
     then run `python docs/gen_protocol.py`. -->
# Протокол розумного програматора PADAUK

Опис для тих, хто пише власного клієнта або порт прошивки. Три частини:

1. [Протокол PC ⇄ програматор](#protocol) — кадри, сесія, команди, операції, події, коди статусу.
2. [Формат пакета прошивки](#package-format) — що клієнт передає й програматор зберігає.
3. [Внутрішні інтерфейси прошивки](#chip-engine) — ядро, рушій мікросхем, живлення, органи керування.

Посилання виду FR-0xx, SC-0xx, R9 ведуть до специфікації
[`specs/001-pc-programmer-protocol`](../specs/001-pc-programmer-protocol/spec.md) (вимоги, критерії успіху,
рішення в `research.md`).

## Версіонування

- **Протокол 1.0.** Версію передає `HELLO` / `GET_INFO` (`proto_major`, `proto_minor`). Інша мажорна версія →
  `PROTO_VERSION`, сесія не відкривається. Мінорна росте, коли додаються команди, події, коди або поля в
  кінці payload: клієнт MUST ігнорувати зайві байти в кінці відповіді, невідомий код команди дає
  `UNKNOWN_COMMAND` без розриву сесії (§3).
- **Формат пакета 1** (`format_version` у заголовку). Невідомий формат → `PKG_HEADER_INVALID`.
- **Можливості збірки** — `GET_INFO.capabilities`: прошивка може не мати частини функцій (наприклад,
  `MEASURE_MASTER` або `PATCH` на F072), клієнт перевіряє біт, перш ніж пропонувати функцію.
- **Таблиця мікросхем** живе лише в прошивці (`LIST_CHIPS`): нова мікросхема не потребує нового клієнта.

## Коди статусу

Повний перелік — [§6 протоколу](#6-коди-статусу): `0x0000` — успіх, `0x01xx` — кадр, сесія й стан
програматора, `0x02xx` — перевірки пакета, `0x03xx` — сховище, `0x04xx` — операції з мікросхемою
(зокрема збої живлення `VDD_FAULT` / `VPP_FAULT`).

## Відповідність `easypdkprog`

Таблиця підкоманд `pdkprog` і команд протоколу, які відповідають підкомандам `easypdkprog`, — [§7
протоколу](#7-відповідність-командам-easypdkprog-fr-030).
"""


def demote(text: str) -> str:
    """Every heading one level down, so each contract becomes a section of one document."""
    return re.sub(r"^(#+) ", lambda m: "#" + m.group(1) + " ", text, flags=re.M)


def build() -> str:
    out = [HEAD]
    for name, anchor in PARTS:
        text = (CONTRACTS / name).read_text(encoding="utf-8").strip()
        out.append(f'\n<a id="{anchor}"></a>\n\n' + demote(text) + "\n")
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if docs/protocol.md is out of date")
    a = ap.parse_args()
    text = build()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/protocol.md is out of date: run python docs/gen_protocol.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
