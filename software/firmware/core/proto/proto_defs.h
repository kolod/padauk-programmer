/* RESULT.warnings bits */
enum {
    PDK_WARN_CALIB_VALUE_COPIED = 1u << 0,
    PDK_WARN_CALIB_SNAPPED = 1u << 1,
    PDK_WARN_MASTER_MODIFIED = 1u << 2,
    PDK_WARN_RESUMED = 1u << 3,
    PDK_WARN_CALIB_FORCED = 1u << 4,
    PDK_WARN_SERIAL_DUPLICATED = 1u << 5,
    PDK_WARN_CALIB_UNRECOGNIZED = 1u << 6,
};

