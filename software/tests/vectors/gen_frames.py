"""Generate shared CRC/COBS/frame test vectors for the firmware (C header) and the client (JSON).

Usage: python gen_frames.py [--json PATH] [--c-header PATH]
The encoder here is an independent reference implementation used only to produce vectors.
"""
import argparse
import json
import os
import random
import struct
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))


def cobs_encode(data: bytes) -> bytes:
    out = bytearray()
    block = bytearray()
    for b in data:
        if b == 0:
            out.append(len(block) + 1)
            out += block
            block.clear()
        else:
            block.append(b)
            if len(block) == 254:
                out.append(255)
                out += block
                block.clear()
    out.append(len(block) + 1)
    out += block
    return bytes(out) + b"\x00"


def frame(ftype, seq, code, status, payload: bytes) -> bytes:
    head = struct.pack("<BBHHHH", ftype, 0, seq, code, status, len(payload)) + payload
    return head + struct.pack("<I", zlib.crc32(head) & 0xFFFFFFFF)


def build():
    rnd = random.Random(1234)
    blob = bytes(rnd.randrange(256) for _ in range(1024))
    crc = [
        {"data": b"123456789".hex(), "crc": 0xCBF43926},
        {"data": "", "crc": 0},
        {"data": blob.hex(), "crc": zlib.crc32(blob) & 0xFFFFFFFF},
    ]
    cobs_inputs = [b"", b"\x00", b"\x11\x00\x22", bytes(range(1, 255)), bytes((i % 255) + 1 for i in range(255)),
                   b"\x00\x00\x00", bytes([7] * 600)]
    cobs = [{"raw": d.hex(), "encoded": cobs_encode(d).hex()} for d in cobs_inputs]
    frames_def = [
        ("req_hello", 1, 1, 0x0001, 0, bytes([1, 0]) + b"test"),
        ("rsp_ok_empty", 2, 1, 0x0001, 0, b""),
        ("evt_progress", 3, 5, 0x8001, 0, bytes([7, 0, 5, 3, 2, 8, 40])),
        ("nak", 4, 0xFFFF, 0, 0x0101, b""),
        ("req_zeros", 1, 0x1234, 0x0011, 0, bytes(300)),
        ("rsp_error", 2, 0xFFFE, 0x0012, 0x0205, bytes([0xFF, 0xFF])),
    ]
    frames = []
    for name, t, seq, code, status, payload in frames_def:
        raw = frame(t, seq, code, status, payload)
        frames.append({"name": name, "type": t, "seq": seq, "code": code, "status": status,
                       "payload": payload.hex(), "decoded": raw.hex(), "encoded": cobs_encode(raw).hex()})
    return {"crc32": crc, "cobs": cobs, "frames": frames}


def c_array(name, hexstr):
    data = bytes.fromhex(hexstr)
    body = ", ".join(f"0x{b:02x}" for b in data) or "0"
    return f"static const uint8_t {name}[] = {{{body}}};\nstatic const size_t {name}_len = {len(data)};\n"


def write_header(v, path):
    lines = ["/* Generated by software/tests/vectors/gen_frames.py — do not edit. */",
             "#ifndef VECTORS_FRAMES_H", "#define VECTORS_FRAMES_H", "#include <stddef.h>", "#include <stdint.h>", ""]
    for i, c in enumerate(v["crc32"]):
        lines.append(c_array(f"vec_crc{i}_data", c["data"]))
        lines.append(f"static const uint32_t vec_crc{i}_value = 0x{c['crc']:08x}u;\n")
    lines.append(f"#define VEC_CRC_COUNT {len(v['crc32'])}\n")
    for i, c in enumerate(v["cobs"]):
        lines.append(c_array(f"vec_cobs{i}_raw", c["raw"]))
        lines.append(c_array(f"vec_cobs{i}_enc", c["encoded"]))
    lines.append(f"#define VEC_COBS_COUNT {len(v['cobs'])}\n")
    for f in v["frames"]:
        n = f["name"]
        lines.append(c_array(f"vec_frame_{n}_decoded", f["decoded"]))
        lines.append(c_array(f"vec_frame_{n}_encoded", f["encoded"]))
        lines.append(c_array(f"vec_frame_{n}_payload", f["payload"]))
        lines.append(f"static const uint16_t vec_frame_{n}_meta[4] = {{0x{f['type']:x}, 0x{f['seq']:x}, "
                     f"0x{f['code']:x}, 0x{f['status']:x}}};\n")
    lines.append("#endif")
    with open(path, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", default=os.path.join(HERE, "frames.json"))
    ap.add_argument("--c-header", default=None)
    args = ap.parse_args()
    v = build()
    with open(args.json, "w", newline="\n") as fh:
        json.dump(v, fh, indent=1)
    if args.c_header:
        write_header(v, args.c_header)


if __name__ == "__main__":
    main()
